unknown, fails = [], []
for clue, exp in TESTS:
    i = ci.get(clue)
    if i is None:
        unknown.append(clue); continue
    order = np.argsort(-Q[i].astype(np.int32))
    names = [T[j] for j in order]
    ok = set(exp.split('/'))
    pos = next((r for r, n in enumerate(names) if n in ok), None)
    for k in (1,3,5):
        if pos is not None and pos < k: rank_hits[k] += 1
    if pos is None or pos >= 3:
        fails.append(f"{clue}→{'/'.join(names[:3])} [기대 {exp}]")

