/**
 * 오늘의 AI·IT 용어 — 데이터와 순환 규칙.
 *
 * ── 왜 Firestore 가 아니라 코드에 박아두나 ──
 * 이건 매일 바뀌지만 "수집"되지 않는다. 뉴스와 정반대다 — 내용이 시의성에 기대지
 * 않으니 한 번 잘 써두면 몇 년을 쓴다. 그래서 서버도, 수집 스크립트도, 교사 화면도
 * 필요 없다. 파일 하나에 넣고 날짜로 골라 쓰는 게 가장 단순하고, 가장 안 고장난다.
 * (뉴스는 매일 새 사실이 필요해서 GitHub Actions 가 필요했다 — 성격이 다르다.)
 *
 * ── 왜 "어디서 만나나"가 있나 ──
 * 용어 사전은 널려 있다. 이 카드가 사전과 다른 점은 학생 생활에 닿는 한 줄이다.
 * GPU 를 "병렬 연산 장치"라고만 쓰면 남는 게 없지만 "게임 그래픽카드와 같은 부품이고
 * AI 때문에 값이 올랐다"고 하면 남는다. 새 용어를 추가할 때 이 칸을 비우지 말 것 —
 * 비울 거면 그 용어는 아직 넣을 준비가 안 된 것이다.
 *
 * ── 순서를 섞지 말 것 ──
 * 순환은 배열 순서를 그대로 따른다. 중간에 끼워 넣으면 그날부터 학생이 보는 용어가
 * 통째로 밀린다(어제 본 게 오늘 또 나올 수 있다). 새 용어는 배열 끝에 붙인다.
 */

