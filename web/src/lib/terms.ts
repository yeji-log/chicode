/**
 * 오늘의 용어.
 *
 * 날짜(자정 기준)로만 고르므로 서버도 저장소도 필요 없고, 같은 날 접속한 학생은
 * 모두 같은 용어를 본다 — 수업 중에 "오늘 용어 봤니"가 성립하려면 이게 중요하다.
 *
 * KST(UTC+9)를 더하고 나누는 이유: 그냥 UTC 로 나누면 날짜가 한국 시각 오전 9시에
 * 바뀐다. 1교시 중에 용어가 갈리면 안 되니 한국 자정에 맞춘다.
 */
export function todayTermIndex(now: number = Date.now()): number {
  const KST_OFFSET_MS = 9 * 60 * 60 * 1000
  const DAY_MS = 24 * 60 * 60 * 1000
  return Math.floor((now + KST_OFFSET_MS) / DAY_MS) % TERMS.length
}

export function todayTerm(now: number = Date.now()): Term {
  return TERMS[todayTermIndex(now)]
}

/**
 * 어제부터 거슬러 올라가며 최근에 지나간 용어들.
 * 배열 앞쪽으로 넘어가다 처음으로 돌아가면 끝에서 이어 받는다(순환).
 */
export function recentTerms(count: number, now: number = Date.now()): Term[] {
  const today = todayTermIndex(now)
  const result: Term[] = []
  for (let step = 1; step <= Math.min(count, TERMS.length - 1); step += 1) {
    result.push(TERMS[(today - step + TERMS.length) % TERMS.length])
  }
  return result
}
